/** Seed data for Iranian Cities */
export const citySeed: SeedTableConfig<SeedCityItem> = {
  tableName: 'City',
  model: City,
  forceInsertBySeed: false,
  uniqueKey: 'title',
  data: rawCities.map((c) => ({
    title: c.title,
    provinceTitle: c.provinceTitle,
    isActive: true,
  })),
  resolveData: async (items: SeedCityItem[]) => {
    const provinces = await Province.find({}, { title: 1, _id: 1 }).lean();
    const provinceMap = new Map(provinces.map((p: any) => [p.title, p._id]));

    return items
      .filter((item) => provinceMap.has(item.provinceTitle))
      .map((item) => ({
        title: item.title,
        provinceId: provinceMap.get(item.provinceTitle),
        isActive: item.isActive ?? true,
        forceInsertBySeed: item.forceInsertBySeed,
      }));
  },
  getItemKey: (item: any) => `${String(item.provinceId || '')}_${item.title}`,
};
